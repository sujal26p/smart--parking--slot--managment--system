CREATE DATABASE IF NOT EXISTS smart_parking_pro CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE smart_parking_pro;
CREATE TABLE IF NOT EXISTS app_users (id INT AUTO_INCREMENT PRIMARY KEY, full_name VARCHAR(100) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE, password_hash VARCHAR(300) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS parking_state (id INT PRIMARY KEY, payload LONGTEXT NOT NULL);
